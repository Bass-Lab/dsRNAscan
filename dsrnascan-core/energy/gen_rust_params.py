"""Generate ../src/turner2004.rs from turner2004.json, profile "duplexfold".

Tables are filled by calling duplex_energy.py's own lookup rules, so the Rust tables cannot drift
from the validated reference evaluator. Energies in dcal/mol (integer kcal/mol x 100), as in
ViennaRNA. Run: python gen_rust_params.py
"""
from pathlib import Path

import duplex_energy as de

T, P = de.T, de.PROFILES["duplexfold"]
NT = "ACGU"
PAIRS = ["AU", "CG", "GC", "GU", "UA", "UG"]  # index order used by src/duplex.rs


def dc(x):
    v = round(x * 100)
    assert abs(v - x * 100) < 1e-6, x
    return v


def arr(x):
    return "[" + ", ".join(arr(v) if isinstance(v, list) else str(v) for v in x) + "]"


def table(name, ty, x, doc):
    return f"/// {doc}\npub const {name}: {ty} = {arr(x)};\n"


out = [
    "// @generated by energy/gen_rust_params.py from energy/turner2004.json (profile \"duplexfold\").\n",
    "// Do not edit. Turner 2004 (NNDB; Mathews et al. 2004 PNAS) with RNA.duplexfold's conventions,\n",
    "// see energy/README.md. Energies in dcal/mol. Pair index: AU CG GC GU UA UG; base index: A C G U.\n\n",
    f"pub const INIT: i32 = {dc(P['init'])};\n",
    f"pub const TERM_AU: i32 = {dc(P['terminal_au'])};\n",
    f"pub const INT_AU: i32 = {dc(T['interior']['au_gu_closure'])};\n",
    f"pub const ASYM_PER_NT: i32 = {dc(T['interior']['asymmetry_per_nt'])};\n",
    f"pub const ASYM_CAP: i32 = {dc(P['asym_cap'])};\n",
    f"pub const MM_1XN: i32 = {dc(T['interior']['mismatch_1xn'])};\n\n",
]
stack = T[P["stack"]]
out.append(table("STACK", "[[i32; 6]; 6]", [[dc(stack[p][q]) for q in PAIRS] for p in PAIRS],
                 "[outer pair][next pair], outer = nearer the 5' end of strand 1"))
tm = T["terminal_mismatch"]
out.append(table("TMM", "[[[i32; 4]; 4]; 6]", [[[dc(tm[p][x][y]) for y in NT] for x in NT] for p in PAIRS],
                 "terminal mismatch [pair top|bottom][X 3' of top][Y 5' of bottom]"))
out.append(table("D3", "[[i32; 4]; 6]", [[dc(T["dangle3"][p][x]) for x in NT] for p in PAIRS],
                 "3' dangle [pair][X 3' of top]"))
out.append(table("D5", "[[i32; 4]; 6]", [[dc(T["dangle5"][p][y]) for y in NT] for p in PAIRS],
                 "5' dangle [pair][Y 5' of bottom]"))
out.append(table("BULGE", "[i32; 31]", [0] + [dc(T["bulge"]["init"][str(n)]) for n in range(1, 31)],
                 "bulge initiation by size (index 0 unused)"))
out.append(table("INT_INIT", "[i32; 31]", [0] * 4 + [dc(T["interior"]["init"][str(n)]) for n in range(4, 31)],
                 "generic interior-loop initiation by total size (indices < 4 unused)"))
g = {**T["interior"]["mismatch_generic"], **P["mm_generic"]}
out.append(table("MM_GENERIC", "[[i32; 4]; 4]", [[dc(g.get(x + y, 0.0)) for y in NT] for x in NT],
                 "generic interior first mismatch [X on the closing pair's 5'->3' strand][Y]"))
out.append(table("MM23", "[[[i32; 4]; 4]; 6]",
                 [[[dc(de.mm23(p, x, y, P)) for y in NT] for x in NT] for p in PAIRS],
                 "2x3 interior first mismatch [closing pair][X][Y]"))
out.append(table("INT11", "[[[[i32; 4]; 4]; 6]; 6]",
                 [[[[dc(T["int11"][o][i][x][yi]) for yi in range(4)] for x in NT] for i in PAIRS] for o in PAIRS],
                 "1x1 loops [outer][inner][strand-1 nt][strand-2 nt]"))
out.append(table("INT21", "[[[[[i32; 4]; 4]; 4]; 6]; 6]",
                 [[[[[dc(T["int21"][o][i][f][x][yi]) for yi in range(4)] for x in NT] for f in NT] for i in PAIRS]
                  for o in PAIRS],
                 "1x2 loops [outer][inner][F][X][Y]: X single nt on strand 1, strand 2 reads Y then F"))
out.append(table("INT22", "[[[[i32; 16]; 16]; 6]; 6]",
                 [[[[dc(v) for v in T["int22"][o][i][x1 + y1]] for x1 in NT for y1 in NT] for i in PAIRS]
                  for o in PAIRS],
                 "2x2 loops [outer][inner][4*X1+X2 next to outer][4*Y1+Y2 next to inner]"))

dest = Path(__file__).resolve().parent.parent / "src" / "turner2004.rs"
dest.write_text("".join(out))
print(f"wrote {dest}")
